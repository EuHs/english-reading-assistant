// Build: copy shared core into extension + server, bundle the userscript, zip the extension.
// Usage: node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);
const SHARED = ['config.js', 'dict.js', 'ai.js', 'text.js', 'annotate.js', 'store.js', 'ui.js', 'settings.js', 'actions.js', 'pdfreader.js'];
const version = JSON.parse(fs.readFileSync(r('extension/manifest.json'), 'utf8')).version;

for (const dest of ['extension/shared', 'server/public/shared']) {
  fs.rmSync(r(dest), { recursive: true, force: true });
  fs.mkdirSync(r(dest), { recursive: true });
  for (const f of SHARED) fs.copyFileSync(r('shared', f), r(dest, f));
}
fs.mkdirSync(r('server/public/data'), { recursive: true });
for (const f of ['dict.json', 'roots.json']) fs.copyFileSync(r('dist', f), r('server/public/data', f));
fs.mkdirSync(r('server/public/lib'), { recursive: true });
fs.copyFileSync(r('extension/lib/pdf.min.js'), r('server/public/lib/pdf.min.js'));
fs.copyFileSync(r('extension/lib/pdf.worker.min.js'), r('server/public/lib/pdf.worker.min.js'));

const CDN = 'https://cdn.jsdelivr.net/gh/EuHs/english-reading-assistant@main';
// full: Tampermonkey / Violentmonkey (desktop, Android, iOS Tampermonkey)
// ios:  Userscripts for Safari — no @resource / menu commands / GM_getValue, GM APIs only in the content world
// Neither declares @require/@resource: those CDN downloads fail silently where jsDelivr is blocked, so pdf.js
// is bundled and the dictionary / pdf.js worker are fetched at runtime from the user's server or mirrors.
const VARIANTS = {
  full: { file: 'english-reading-assistant.user.js', name: '英语阅读助手 English Reading Assistant', meta: [
    '@grant        GM_xmlhttpRequest', '@grant        GM_getValue', '@grant        GM_setValue', '@grant        GM_registerMenuCommand',
    '@grant        GM.xmlHttpRequest', '@grant        GM.getValue', '@grant        GM.setValue',
    '@grant        GM.registerMenuCommand', '@connect      *'] },
  ios: { file: 'english-reading-assistant.ios.user.js', name: '英语阅读助手 English Reading Assistant (iOS Userscripts)', meta: [
    '@grant        GM.xmlHttpRequest', '@grant        GM_xmlhttpRequest', '@grant        GM.getValue', '@grant        GM.setValue',
    '@inject-into  content'] },
};
const shared = SHARED.map((f) => `// ---- shared/${f} ----\n` + fs.readFileSync(r('shared', f), 'utf8'));
// expected SHA-256 of files the userscript downloads, checked before use (see platform.user.js)
const sha256 = (f) => crypto.createHash('sha256').update(fs.readFileSync(r(f))).digest('hex');
const assetHashes = `const ASSET_SHA256 = ${JSON.stringify({ 'dict.json': sha256('dist/dict.json'), 'roots.json': sha256('dist/roots.json'), 'pdf.worker.min.js': sha256('extension/lib/pdf.worker.min.js') })};\n`;
const platform = assetHashes + fs.readFileSync(r('userscript/platform.user.js'), 'utf8');
// run on first PDF open with module/exports/define shadowed, so a page's AMD loader can't capture it
const pdfMin = fs.readFileSync(r('extension/lib/pdf.min.js'), 'utf8');
const pdfjs = `// ---- pdf.js ${pdfMin.match(/const version="([^"]+)"/)[1]} (Apache-2.0, extension/lib/pdf.min.js) ----
function loadBundledPdfjs() {
  const module = { exports: {} }, exports = module.exports, define = undefined;
${pdfMin}
  return module.exports;
}`;
for (const v of Object.values(VARIANTS)) {
  const url = `${CDN}/userscript/${v.file}`;
  const header = ['==UserScript==', `@name         ${v.name}`, '@namespace    https://github.com/EuHs/english-reading-assistant', `@version      ${version}`,
    '@description  网页/PDF 英语阅读：划词翻译、高亮下划线批注、离线词典、AI 词根与时态分析、语法分析、生词本与好词好句（服务器同步）。适配手机端。',
    '@author       EuHs', '@license      MIT', '@match        *://*/*', ...v.meta,
    '@homepageURL  https://github.com/EuHs/english-reading-assistant', `@downloadURL  ${url}`, `@updateURL    ${url}`,
    '@run-at       document-idle', '@noframes', '==/UserScript=='].map((l) => '// ' + l).join('\n');
  const body = [...shared, '// ---- userscript/platform.user.js ----\n' + platform, pdfjs].join('\n');
  // Own scope so ERA does not leak into the page (globalThis inside a TM sandbox is the sandbox)
  fs.writeFileSync(r('userscript', v.file), header + '\n/* Generated by tools/build.mjs from shared/*.js + userscript/platform.user.js + pdf.js — edit those files, not this one. */\n(function () {\n\'use strict\';\n' + body + '\n})();\n');
}

fs.mkdirSync(r('dist'), { recursive: true });
const zip = r('dist', `english-reading-assistant-extension-v${version}.zip`);
fs.rmSync(zip, { force: true });
execSync(`cd "${r('extension')}" && zip -qr "${zip}" . -x "*.DS_Store"`);
console.log('built userscript + extension zip v' + version);

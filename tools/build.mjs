// Build: copy shared core into extension + server, bundle the userscript, zip the extension.
// Usage: node tools/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { execSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const r = (...p) => path.join(root, ...p);
const SHARED = ['config.js', 'dict.js', 'ai.js', 'text.js', 'annotate.js', 'store.js', 'ui.js', 'settings.js', 'actions.js', 'pdfreader.js'];
const version = JSON.parse(fs.readFileSync(r('extension/manifest.json'), 'utf8')).version;

for (const dest of ['extension/shared', 'server/public/shared']) {
  fs.rmSync(r(dest), { recursive: true, force: true });
  fs.mkdirSync(r(dest), { recursive: true });
  for (const f of SHARED) fs.copyFileSync(r('shared', f), r(dest, f));
}
fs.mkdirSync(r('server/public/data'), { recursive: true });
for (const f of ['dict.json', 'roots.json']) fs.copyFileSync(r('dist', f), r('server/public/data', f));
fs.mkdirSync(r('server/public/lib'), { recursive: true });
fs.copyFileSync(r('extension/lib/pdf.min.js'), r('server/public/lib/pdf.min.js'));
fs.copyFileSync(r('extension/lib/pdf.worker.min.js'), r('server/public/lib/pdf.worker.min.js'));

const header = `// ==UserScript==
// @name         英语阅读助手 English Reading Assistant
// @namespace    https://github.com/EuHs/english-reading-assistant
// @version      ${version}
// @description  网页/PDF 英语阅读：划词翻译、高亮下划线批注、离线词典、AI 词根与时态分析、语法分析、生词本与好词好句（服务器同步）。适配手机端。
// @author       EuHs
// @license      MIT
// @match        *://*/*
// @grant        GM_xmlhttpRequest
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        GM_registerMenuCommand
// @grant        GM_getResourceText
// @grant        GM.xmlHttpRequest
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM.registerMenuCommand
// @connect      *
// @resource     dict https://cdn.jsdelivr.net/gh/EuHs/english-reading-assistant@main/dist/dict.json
// @resource     roots https://cdn.jsdelivr.net/gh/EuHs/english-reading-assistant@main/dist/roots.json
// @require      https://cdn.jsdelivr.net/npm/pdfjs-dist@3.11.174/build/pdf.min.js
// @homepageURL  https://github.com/EuHs/english-reading-assistant
// @downloadURL  https://cdn.jsdelivr.net/gh/EuHs/english-reading-assistant@main/userscript/english-reading-assistant.user.js
// @updateURL    https://cdn.jsdelivr.net/gh/EuHs/english-reading-assistant@main/userscript/english-reading-assistant.user.js
// @run-at       document-idle
// @noframes
// ==/UserScript==
/* Generated by tools/build.mjs from shared/*.js + userscript/platform.user.js — edit those files, not this one. */
`;
const body = [...SHARED.map((f) => `// ---- shared/${f} ----\n` + fs.readFileSync(r('shared', f), 'utf8')), '// ---- userscript/platform.user.js ----\n' + fs.readFileSync(r('userscript/platform.user.js'), 'utf8')].join('\n');
// Own scope so ERA does not leak into the page (globalThis inside a TM sandbox is the sandbox)
fs.writeFileSync(r('userscript/english-reading-assistant.user.js'), header + '(function () {\n\'use strict\';\n' + body + '\n})();\n');

fs.mkdirSync(r('dist'), { recursive: true });
const zip = r('dist', `english-reading-assistant-extension-v${version}.zip`);
fs.rmSync(zip, { force: true });
execSync(`cd "${r('extension')}" && zip -qr "${zip}" . -x "*.DS_Store"`);
console.log('built userscript + extension zip v' + version);
